<h3>Дифтонги и особые случаи</h3>
<ul>
<li><b>ea</b> ≈ мягкое «я»: seară [ся́ръ] — вечер, dimineață — утро.</li>
<li><b>ia</b> ≈ «я»: iarnă [я́рнъ] — зима.</li>
<li><b>oa</b> ≈ быстрое «уа»: floare [флуа́ре] — цветок, școală — школа.</li>
